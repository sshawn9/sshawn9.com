import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sectionCount = 72;
const paragraph =
  '车辆轨迹与参考路径的局部关系不能只用一个瞬时误差概括。沿轨迹推进时，航向误差、横向偏差和参考曲率会共同改变弧长换算率；交互图需要保留同一组参数，才能把单因素变化与耦合变化区分开。这里使用确定性的静态正文扩展最差路径，确保两个候选接收完全相同的 HTML 负载，并且正文不会被复制到客户端数据载荷中。';

const headings = Array.from({ length: sectionCount }, (_, index) => ({
  id: 'analysis-' + String(index + 1).padStart(2, '0'),
  title: String(index + 1) + '. 局部弧长换算的连续性检验',
}));

function renderSection({ id, title }, index, interactiveMarkup, slotName) {
  return [
    '      <section' +
      (slotName ? ' slot="' + slotName + '"' : '') +
      ' class="article-section" id="' +
      id +
      '">',
    '        <h2>' + title + '</h2>',
    '        <p>' + paragraph + '</p>',
    '        <p>' +
      paragraph +
      '第 ' +
      String(index + 1) +
      ' 组采样只改变观测窗口，不改变页面结构。</p>',
    index === 2 ? '        ' + interactiveMarkup : '',
    '      </section>',
  ]
    .filter(Boolean)
    .join('\n');
}

const tocSource = JSON.stringify(headings, null, 2);
const astroSections = headings
  .map((heading, index) =>
    renderSection(
      heading,
      index,
      '<InteractiveDiagram client:visible />',
      index === 0 ? 'initial-frame' : undefined,
    ),
  )
  .join('\n');
const qwikSections = headings
  .map((heading, index) => renderSection(heading, index, '<InteractiveDiagram />'))
  .join('\n');

const astroSource =
  [
    '---',
    '// Generated by scripts/generate-fixtures.mjs. Do not edit directly.',
    "import BaseLayout from '../../../layouts/BaseLayout.astro';",
    "import ArticlePage from '../../../components/ArticlePage.astro';",
    "import InteractiveDiagram from '../../../components/InteractiveDiagram.svelte';",
    "import { article } from '@poc-shared/fixture-data';",
    '',
    'const toc = ' + tocSource + ';',
    '---',
    '',
    '<BaseLayout title={article.title} description={article.description} pageKind="article">',
    '  <ArticlePage article={article} toc={toc}>',
    astroSections,
    '  </ArticlePage>',
    '</BaseLayout>',
  ].join('\n') + '\n';

const qwikSource =
  [
    '// Generated by scripts/generate-fixtures.mjs. Do not edit directly.',
    "import { component$, RenderOnce } from '@builder.io/qwik';",
    "import type { DocumentHead } from '@builder.io/qwik-city';",
    "import { article } from '@poc-shared/fixture-data';",
    "import { ArticlePage } from '~/components/article-page/article-page';",
    "import { InteractiveDiagram } from '~/components/interactive-diagram/interactive-diagram';",
    '',
    'const toc = ' + tocSource + ';',
    '',
    'export default component$(() => (',
    '  <ArticlePage article={article} toc={toc}>',
    '    <RenderOnce>',
    qwikSections,
    '    </RenderOnce>',
    '  </ArticlePage>',
    '));',
    '',
    'export const head: DocumentHead = {',
    '  title: article.title,',
    "  meta: [{ name: 'description', content: article.description }],",
    '};',
  ].join('\n') + '\n';

const targets = [
  ['apps/astro/src/pages/zh/blog/frenet-poc.astro', astroSource],
  ['apps/qwik/src/routes/zh/blog/frenet-poc/index.tsx', qwikSource],
  [
    'shared/generated/fixture-stats.json',
    JSON.stringify(
      {
        sectionCount,
        bodyProbe: paragraph.slice(0, paragraph.indexOf('。') + 1),
        sourceCharacters: {
          astro: astroSource.length,
          qwik: qwikSource.length,
        },
      },
      null,
      2,
    ) + '\n',
  ],
];

for (const [relativePath, contents] of targets) {
  const target = resolve(root, relativePath);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, contents, 'utf8');
}

console.log(
  'Generated ' + String(sectionCount) + ' deterministic article sections for both candidates.',
);
